"""Generates install/SkyboundInstaller.luau: one Luau script that creates every Skybound
script inside the place currently open in Roblox Studio (paste it into the Command Bar,
or run it through the Studio MCP connection).

Mirrors default.project.json. Run from the skybound folder:  python tools/make_installer.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (source folder, service path, instance name) — same mapping as default.project.json
TARGETS = [
    ("src/shared", ["ReplicatedStorage"], "Skybound"),
    ("src/server", ["ServerScriptService"], "SkyboundServer"),
    ("src/client", ["StarterPlayer", "StarterPlayerScripts"], "SkyboundClient"),
]

INIT_CLASSES = {"init.server.luau": "Script", "init.client.luau": "LocalScript", "init.luau": "ModuleScript"}


def file_class(filename):
    if filename.endswith(".server.luau"):
        return "Script", filename[: -len(".server.luau")]
    if filename.endswith(".client.luau"):
        return "LocalScript", filename[: -len(".client.luau")]
    return "ModuleScript", filename[: -len(".luau")]


def lua_string(text):
    level = 1
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    # A newline right after the opening bracket is dropped by Lua, so add one to keep text exact.
    return "[" + eq + "[\n" + text + "]" + eq + "]"


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


lines = []
counter = [0]


def emit_node(path, name, parent_ref):
    counter[0] += 1
    ref = "n[%d]" % counter[0]
    entries = sorted(os.listdir(path))
    init = next((e for e in entries if e in INIT_CLASSES), None)
    if init:
        lines.append('%s = make("%s", "%s", %s, %s)' % (ref, INIT_CLASSES[init], name, parent_ref, lua_string(read(os.path.join(path, init)))))
    else:
        lines.append('%s = make("Folder", "%s", %s)' % (ref, name, parent_ref))
    for entry in entries:
        full = os.path.join(path, entry)
        if entry == init:
            continue
        if os.path.isdir(full):
            emit_node(full, entry, ref)
        elif entry.endswith(".luau"):
            cls, child = file_class(entry)
            counter[0] += 1
            lines.append('n[%d] = make("%s", "%s", %s, %s)' % (counter[0], cls, child, ref, lua_string(read(full))))


for src, service_path, name in TARGETS:
    parent = 'game:GetService("%s")' % service_path[0]
    for child in service_path[1:]:
        parent += ':FindFirstChild("%s")' % child
    counter[0] += 1
    lines.append("n[%d] = %s" % (counter[0], parent))
    lines.append('removeExisting(n[%d], "%s")' % (counter[0], name))
    emit_node(os.path.join(ROOT, src), name, "n[%d]" % counter[0])

header = '''-- SKYBOUND INSTALLER — generated by tools/make_installer.py from src/. Do not edit by hand.
-- Creates (or replaces) the Skybound scripts in the place open in Roblox Studio:
--   ReplicatedStorage.Skybound, ServerScriptService.SkyboundServer,
--   StarterPlayer.StarterPlayerScripts.SkyboundClient
-- Nothing else in the place is changed. Undo with Ctrl+Z.
-- Undo support (Ctrl+Z). Optional: the install still works if this is unavailable.
local okRecord, ChangeHistoryService, recording = pcall(function()
	local service = game:GetService("ChangeHistoryService")
	return service, service:TryBeginRecording("Install Skybound")
end)

local n = {}
local count = 0
local function make(className, name, parent, source)
	local instance = Instance.new(className)
	instance.Name = name
	if source then
		instance.Source = source
	end
	instance.Parent = parent
	count += 1
	return instance
end
local function removeExisting(parent, name)
	local old = parent:FindFirstChild(name)
	if old then
		old:Destroy()
	end
end
'''

footer = '''
if okRecord and recording then
	ChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit)
end
print(("[Skybound] Installed %d instances. Press Play to test."):format(count))
'''

out = os.path.join(ROOT, "install", "SkyboundInstaller.luau")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(header + "\n".join(lines) + "\n" + footer)
print("wrote", out, "(%d instances)" % (counter[0] - len(TARGETS)))
